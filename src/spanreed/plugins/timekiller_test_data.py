"""What the Timekiller plugin did before it became workflows.

Made by running the plugin for one user, once for each case below.

A case says what was run (``run``: ``journal``, ``mood``, ``books``,
``scans``, ``push`` for what the plugin did by itself, ``by hand`` for its
command) and the user's ``answers`` in order: a number is the place of a
choice, a text is what was written, and ``done`` is the last choice. It can
also say what there was: ``properties`` of notes by ``path|property``,
``books`` being read as ``[path, title]`` (two by default), ``files`` in the
scans folder (four by default), names that are ``taken``, the ``heading``
for journaling, what the plugin ``memory`` held, and for a push the activity
that was picked at random (``pick``). A case with ``times`` ran that often
in a row.

Each line of what the plugin did is one thing, in order:

- ``["choice", question, choices, columns, the place of the answer]``
- ``["input", question, answer]``
- ``["say", message]`` and ``["file", name]``: a message, and a file sent.
- ``["create"]``: today's daily note was asked for.
- ``["get", note, property]`` and ``["set", note, property, value]``
- ``["append", note, text, heading]``
- ``["query"]``: the vault was asked for the books being read.
- ``["list", folder]``, ``["read", path]``, ``["delete", path]`` and
  ``["move", from, to]``
- ``["remember", name]``: the plugin kept something for later.
- ``["on offer", names]``: the activities one was picked from at random.
- ``["again"]``: the next time of the case starts here.

``<today>`` and ``<yesterday>`` stand for the dates when it ran. The
journaling prompts were picked in their order, not at random.
"""

